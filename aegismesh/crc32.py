"""IEEE 802.3 CRC-32 (reflected polynomial 0xEDB88320), computed bitwise.

The 256-entry lookup table is generated by running the bit-by-bit polynomial
division once; per-byte work then uses the table. `crc32_bitwise` is the
reference implementation used by the tests to cross-check the table.
"""

POLY = 0xEDB88320


def _make_table():
    table = []
    for byte in range(256):
        crc = byte
        for _ in range(8):
            crc = (crc >> 1) ^ POLY if crc & 1 else crc >> 1
        table.append(crc)
    return tuple(table)


_TABLE = _make_table()


def crc32(data: bytes, crc: int = 0) -> int:
    crc ^= 0xFFFFFFFF
    for b in data:
        crc = _TABLE[(crc ^ b) & 0xFF] ^ (crc >> 8)
    return crc ^ 0xFFFFFFFF


def crc32_bitwise(data: bytes) -> int:
    crc = 0xFFFFFFFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ POLY if crc & 1 else crc >> 1
    return crc ^ 0xFFFFFFFF
